"""Pin portable identifier properties to Python 3.13's Unicode repertoire."""

import json
import sys
import unicodedata
from collections.abc import Callable
from pathlib import Path


def generate() -> None:
    if sys.version_info[:2] != (3, 13) or unicodedata.unidata_version != '15.1.0':
        sys.exit('Generate identifier ranges using Python 3.13 / Unicode 15.1.0')
    lowercase, digits = ranges(str.islower), ranges(str.isdigit)
    value = {
        'unicode_version': unicodedata.unidata_version,
        'lowercase': lowercase,
        'digits': digits,
    }
    destination = Path(__file__).parents[1] / 'ufor' / 'identifier_ranges.json'
    destination.write_text(json.dumps(value, indent=2) + '\n')
    source = (
        '// Generated by schema/generate_identifiers.py; '
        f'Unicode {unicodedata.unidata_version}.\n'
    )
    for name, pairs in [('LOWERCASE', lowercase), ('DIGITS', digits)]:
        source += f'pub(crate) const {name}: &[[u32; 2]] = &[\n'
        source += ''.join(f'    [{a}, {b}],\n' for a, b in pairs)
        source += '];\n'
    rust = Path(__file__).parents[1] / 'crates/ufor/src/identifier_ranges.rs'
    rust.write_text(source)


def ranges(predicate: Callable[[str], bool]) -> list[list[int]]:
    result: list[list[int]] = []
    for point in range(sys.maxunicode + 1):
        if predicate(chr(point)):
            if result and result[-1][1] == point - 1:
                result[-1][1] = point
            else:
                result.append([point, point])
    return result


if __name__ == '__main__':
    generate()
